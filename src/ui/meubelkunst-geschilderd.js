// Dit is geen vertaling van de oude set. De oude tekeningen zijn gebouwd uit
// rechthoeken: `M17 6h14v2H17Z`, kaarsrecht, haaks, met één kleur. Die vorm is
// de helft van waarom het stram oogt - de andere helft was het licht, en dat
// zit in geschilderd.js.
//
// Hier staat geen enkele haakse rechthoek in. Een kast loopt naar boven iets
// taps toe, een plank zakt door, een poot wordt naar onder dunner. Die
// kromming komt uit vormen.js, zodat zeventig meubelstukken niet zeventig
